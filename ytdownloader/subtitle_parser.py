def _parse_json3_caption(json3_content: str) -> list[SubtitleCue]:
    """Extract subtitle cues from YouTube's json3 caption format.

    The json3 format is a JSON object with an ``"events"`` array.  Each
    event has ``t`` (start offset in milliseconds), ``d`` (duration in
    milliseconds), and ``segs`` (an array of ``{"utf8": "..."}`` dicts).

    Args:
        json3_content: Raw json3 string from the YouTube subtitle endpoint.

    Returns:
        Ordered list of :class:`SubtitleCue` objects.
    """
    cues: list[SubtitleCue] = []

    try:
        data = _safe_json_loads(json3_content)
    except (ValueError, TypeError) as exc:
        _logger.error("Failed to parse json3 caption: %s", exc)
        return cues

    events: list[dict] = _get_nested(data, _JSON3_EVENTS_KEY, default=[])

    cue_index = 0
    for event in events:
        if not isinstance(event, dict):
            continue

        event_type = event.get("_gtsv", "") or event.get("type", "")
        if event_type and event_type not in ("", "text"):
            continue

        start_ms_raw = event.get("t", 0)
        duration_ms_raw = event.get("d", 0)
        segs: list[dict] = event.get("segs", [])

        if not segs:
            continue

        try:
            start_ms = int(start_ms_raw)
        except (TypeError, ValueError):
            start_ms = 0

        try:
            duration_ms = int(duration_ms_raw)
        except (TypeError, ValueError):
            duration_ms = 0

        text_parts: list[str] = []
        for seg in segs:
            if isinstance(seg, dict):
                utf8_chunk = seg.get(_JSON3_UTF8_KEY, "")
                if utf8_chunk:
                    text_parts.append(utf8_chunk)

        raw_text = "".join(text_parts)
        text = _normalise_subtitle_text(raw_text.strip())

        if not text:
            continue

        end_ms = start_ms + max(duration_ms, _estimate_duration_ms(text))

        cue = SubtitleCue(index=cue_index, start_ms=start_ms, end_ms=end_ms, text=text)
        cues.append(cue)
        cue_index += 1

    _logger.debug("Parsed %d json3 cue(s).", len(cues))
    return cues


def _json3_cue_to_srt(cue: SubtitleCue, index: int) -> str:
    """Convert a single json3-sourced :class:`SubtitleCue` to SRT entry.

    Identical to :func:`_xml_cue_to_srt` but separated for clarity and
    future format-specific customisation.

    Args:
        cue: The subtitle cue to convert.
        index: The 1-based SRT entry index.

    Returns:
        A string in SRT entry format.
    """
    return _xml_cue_to_srt(cue, index)


