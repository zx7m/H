def parse_caption_tracks(captions_data: dict) -> list[SubtitleTrack]:
    """Parse the ``captions`` block of a YouTube player response.

    The *captions_data* argument should be the value of
    ``player_response["captions"]``.  Returns an empty list when the block
    is absent or contains no tracks.

    Args:
        captions_data: The ``"captions"`` dict from a YouTube player response.

    Returns:
        A (possibly empty) list of :class:`SubtitleTrack` objects.

    Raises:
        SubtitleError: If *captions_data* is not a mapping.
    """
    if not isinstance(captions_data, dict):
        _logger.warning(
            "Expected captions_data to be a dict; got %s. Returning empty list.",
            type(captions_data).__name__,
        )
        return []

    renderer: dict = captions_data.get(_CAPTION_PLAYER_KEY, {})
    tracks_raw: list[dict] = renderer.get(_CAPTION_TRACKS_LIST_KEY, [])

    if not tracks_raw:
        _logger.debug("No caption tracks found in captions_data.")
        return []

    tracks: list[SubtitleTrack] = []
    for entry in tracks_raw:
        track = _parse_single_caption_entry(entry)
        if track is not None:
            tracks.append(track)

    _logger.info("Found %d caption track(s).", len(tracks))
    return tracks


def get_caption_tracks(player_response: dict) -> list[SubtitleTrack]:
    """Extract caption tracks directly from a YouTube player response dict.

    This is the preferred entry point for callers who already have the full
    ``ytInitialPlayerResponse`` object.  Handles missing or malformed data
    gracefully by returning an empty list.

    Args:
        player_response: The full YouTube player response dictionary
            (typically the ``ytInitialPlayerResponse`` JavaScript object).

    Returns:
        A (possibly empty) list of :class:`SubtitleTrack` objects.
    """
    if not isinstance(player_response, dict):
        _logger.warning(
            "Expected player_response to be a dict; got %s. Returning empty list.",
            type(player_response).__name__,
        )
        return []

    captions_data: dict = player_response.get(_CAPTION_TRACKS_KEY, {})
    return parse_caption_tracks(captions_data)


def list_available_tracks(
    tracks: list[SubtitleTrack],
) -> list[dict[str, Any]]:
    """Return a human-readable summary of available caption tracks.

    Args:
        tracks: A list of :class:`SubtitleTrack` objects.

    Returns:
        A list of dicts with keys ``index``, ``lang_code``, ``lang``,
        ``is_auto``, ``is_translated``, and ``kind``.
    """
    result: list[dict[str, Any]] = []
    for idx, track in enumerate(tracks):
        result.append(
            {
                "index": idx,
                "lang_code": track.lang_code,
                "lang": track.lang,
                "is_auto": track.is_auto,
                "is_translated": track.is_translated,
                "kind": track.kind or "(manual)",
            }
        )
    return result


