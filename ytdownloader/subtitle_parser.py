@dataclass
class SubtitleTrack:
    """Represents a single YouTube caption or subtitle track.

    Attributes:
        url: Direct URL to the subtitle file (XML or json3 format).
        lang: Human-readable language name (e.g. ``"English"``).
        lang_code: BCP-47 language code (e.g. ``"en"``, ``"es-419"``).
        is_auto: ``True`` when the track was auto-generated by YouTube's ASR.
        is_translated: ``True`` when the track is a machine translation.
        kind: ``"asr"`` for auto-generated, ``"forced"`` for forced, or
            ``None``/empty for manually uploaded captions.
    """

    url: str
    lang: str
    lang_code: str
    is_auto: bool = False
    is_translated: bool = False
    kind: str = ""

    def __post_init__(self) -> None:
        if not self.url:
            raise ValueError("SubtitleTrack.url must be a non-empty string.")
        if not self.lang_code:
            raise ValueError("SubtitleTrack.lang_code must be a non-empty string.")

    def __repr__(self) -> str:
        flags = []
        if self.is_auto:
            flags.append("auto")
        if self.is_translated:
            flags.append("translated")
        if self.kind:
            flags.append(f"kind={self.kind!r}")
        flag_str = f" [{', '.join(flags)}]" if flags else ""
        return (
            f"SubtitleTrack(lang={self.lang_code!r}, "
            f"name={self.lang!r}{flag_str}, url={self.url[:60]!r}...)"
        )


@dataclass
class SubtitleCue:
    """A single timed subtitle cue extracted from a caption file.

    Attributes:
        index: Zero-based index of this cue within the subtitle file.
        start_ms: Start time in milliseconds.
        end_ms: End time in milliseconds.
        text: The subtitle text.  Newlines within a cue are represented as
            ``\\n`` and will be rendered as separate SRT lines.
    """

    index: int
    start_ms: int
    end_ms: int
    text: str = ""

    def __post_init__(self) -> None:
        if self.end_ms <= self.start_ms:
            self.end_ms = self.start_ms + 1000

    @property
    def start_seconds(self) -> float:
        """Start time as floating-point seconds."""
        return self.start_ms / 1000.0

    @property
    def end_seconds(self) -> float:
        """End time as floating-point seconds."""
        return self.end_ms / 1000.0

    def __repr__(self) -> str:
        return (
            f"SubtitleCue(index={self.index}, "
            f"start={self.start_seconds:.3f}s, end={self.end_seconds:.3f}s, "
            f"text={self.text[:30]!r})"
        )


