def download_subtitle(
    track: SubtitleTrack,
    output_path: str,
    format: str = "srt",
    http_client: Any = None,
) -> str:
    """Download a subtitle track and convert it to the requested format.

    The file is fetched from ``track.url``, automatically detected as XML or
    json3, converted to the requested *format*, and written to *output_path*.

    Args:
        track: The :class:`SubtitleTrack` to download.
        output_path: Destination file path.  Parent directories are created
            automatically.  The extension may be omitted; the function appends
            ``.srt`` when *format* is ``"srt"``.
        format: Output format.  Currently only ``"srt"`` is supported.
        http_client: Optional pre-configured HTTP client with a ``get`` method
            compatible with :class:`requests.Session.get`.  When ``None`` a
            plain :class:`requests.Session` is used.

    Returns:
        The absolute path of the written file.

    Raises:
        SubtitleError: If the download fails, the format is unrecognised, or
            conversion to the requested format is not possible.
        ValueError: If *format* is not supported.
    """
    _logger.info(
        "Downloading subtitle track: lang=%s, is_auto=%s, format=%s",
        track.lang_code,
        track.is_auto,
        format,
    )

    format = format.lower().strip()
    if format not in ("srt",):
        raise ValueError(
            f"Unsupported subtitle format: {format!r}. " "Only 'srt' is currently supported."
        )

    output_abs = os.path.abspath(output_path)
    output_dir = os.path.dirname(output_abs)
    if output_dir:
        os.makedirs(output_dir, exist_ok=True)

    base, ext = os.path.splitext(output_abs)
    if format == "srt" and not ext:
        output_abs = f"{base}.srt"

    session = http_client if http_client is not None else requests.Session()

    try:
        response = session.get(
            track.url,
            timeout=_DEFAULT_TIMEOUT,
            headers={
                "User-Agent": (
                    "Mozilla/5.0 (Windows NT 10.0; Win64; x64) "
                    "AppleWebKit/537.36 (KHTML, like Gecko) "
                    "Chrome/120.0.0.0 Safari/537.36"
                ),
                "Referer": "https://www.youtube.com/",
                "Accept": "*/*",
            },
        )
        response.raise_for_status()
        raw_content: str = response.text
    except requests.exceptions.RequestException as exc:
        raise SubtitleError(
            f"Failed to download subtitle from {track.url!r}.",
            cause=exc,
        ) from exc

    detected_format = _detect_format(raw_content, track.url)
    _logger.debug("Detected subtitle format: %s", detected_format)

    try:
        if detected_format == "xml":
            cues = _parse_xml_caption(raw_content)
        elif detected_format == "json3":
            cues = _parse_json3_caption(raw_content)
        else:
            raise SubtitleError(
                f"Cannot parse subtitle format {detected_format!r} from {track.url!r}."
            )
    except SubtitleError:
        raise
    except Exception as exc:
        raise SubtitleError(
            f"Failed to parse subtitle content from {track.url!r}.",
            cause=exc,
        ) from exc

    if not cues:
        _logger.warning("Subtitle file contained no cues: %s", track.url)

    srt_content = convert_to_srt(cues)

    try:
        with open(output_abs, "w", encoding="utf-8") as fh:
            fh.write(srt_content)
    except OSError as exc:
        raise SubtitleError(
            f"Cannot write subtitle to {output_abs!r}: {exc}"
        ) from exc

    file_size = os.path.getsize(output_abs)
    _logger.info(
        "Subtitle saved: %s (%d bytes, %d cue(s)).",
        output_abs,
        file_size,
        len(cues),
    )
    return output_abs


def convert_to_srt(cues: list[SubtitleCue]) -> str:
    """Convert a list of :class:`SubtitleCue` objects to an SRT string.

    Args:
        cues: Ordered list of subtitle cues.

    Returns:
        A complete SRT file content as a string.
    """
    parts: list[str] = []
    for cue in cues:
        parts.append(_cue_to_srt_entry(cue))
    return "\n".join(parts) + "\n" if parts else ""


