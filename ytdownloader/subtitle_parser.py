def _detect_format(content: str, url: str) -> str:
    """Detect whether a subtitle payload is YouTube XML or json3 format.

    Detection order:
    1. Inspect the first non-whitespace character of *content*.
    2. Fall back to the URL extension.

    Args:
        content: Raw subtitle file content.
        url: Source URL (used for extension-based fallback).

    Returns:
        ``"xml"`` or ``"json3"``.
    """
    stripped = content.lstrip()
    if stripped.startswith("<?xml") or stripped.startswith("<"):
        return "xml"
    if stripped.startswith("{") or stripped.startswith("["):
        return "json3"
    parsed = urlparse(url)
    path_lower = parsed.path.lower()
    if path_lower.endswith(".xml") or "xml" in path_lower:
        return "xml"
    if path_lower.endswith(".json3") or "json3" in path_lower:
        return "json3"
    return "xml"


