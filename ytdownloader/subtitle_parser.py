"""
Subtitle and closed-caption parser for the ytdownloader package.

Handles parsing of YouTube caption tracks from player responses, downloading
subtitle files in YouTube's native XML or json3 formats, and converting them
to the widely-supported SubRip (SRT) format.

Typical usage::

    from ytdownloader.subtitle_parser import (
        SubtitleTrack,
        get_caption_tracks,
        download_subtitle,
    )

    tracks = get_caption_tracks(player_response)
    for track in tracks:
        path = download_subtitle(track, "subtitles/", format="srt")
        print(f"Saved: {path}")
"""

