def _parse_single_caption_entry(entry: dict) -> Optional[SubtitleTrack]:
    """Parse one element of the ``captionTracks`` list.

    Each entry has the form::

        {
            "baseUrl": "https://...",
            "name": {"simpleText": "English", "runs": [...]},
            "vssId": ".en",
            "languageCode": "en",
            "kind": "asr",          # optional
            "isTranslatable": true  # optional
        }

    Args:
        entry: Raw dict from ``captionTracks``.

    Returns:
        A :class:`SubtitleTrack`, or ``None`` if the entry is malformed.
    """
    if not isinstance(entry, dict):
        _logger.warning("Skipping malformed caption entry (not a dict): %r", entry)
        return None

    url: str = entry.get("baseUrl", "")
    if not url:
        _logger.warning("Skipping caption entry with empty baseUrl: %r", entry)
        return None

    name_obj: dict = entry.get("name", {})
    if isinstance(name_obj, dict):
        lang: str = name_obj.get("simpleText", name_obj.get("runs", [{}])[0].get("text", ""))
    elif isinstance(name_obj, str):
        lang = name_obj
    else:
        lang = ""

    vss_id: str = entry.get("vssId", "")
    lang_code = _extract_lang_code(vss_id, entry.get("languageCode", ""))

    kind: str = entry.get("kind", "") or ""
    is_translatable: bool = bool(entry.get("isTranslatable", False))

    is_auto: bool = kind == "asr" or (not kind and not lang)
    is_translated: bool = is_translatable and bool(lang_code) and bool(lang)

    return SubtitleTrack(
        url=url,
        lang=lang or lang_code,
        lang_code=lang_code,
        is_auto=is_auto,
        is_translated=is_translated,
        kind=kind,
    )


def _extract_lang_code(vss_id: str, fallback: str) -> str:
    """Extract the BCP-47 language code from a ``vssId`` field.

    YouTube ``vssId`` values look like ``".en"``, ``".es-419"``, or
    ``".a.id"`` (for Indonesian auto-generated).  The leading dot is
    stripped.

    Args:
        vss_id: The raw ``vssId`` string from the caption entry.
        fallback: Value to return when *vss_id* does not contain a code.

    Returns:
        A clean language code string.
    """
    if not vss_id:
        return fallback or "unknown"
    code = vss_id.lstrip(".")
    if not code:
        return fallback or "unknown"
    return code


