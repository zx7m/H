def _clean_subtitle_url(url: str) -> str:
    """Remove unnecessary query parameters from a subtitle URL.

    Strips tracking parameters that may cause problems when downloading
    subtitle files, while preserving the essential ``baseUrl`` components.

    Args:
        url: Raw subtitle URL.

    Returns:
        Cleaned URL string.
    """
    parsed = urlparse(url)
    keep_params = {
        "baseurl",
        "expire",
        "signature",
        "sig",
        "n",
        "player",
        "title",
    }
    qp = parse_qs(parsed.query, keep_blank_values=True)
    filtered = {k: v for k, v in qp.items() if k.lower() in keep_params}
    new_query = urlencode(filtered, doseq=True)
    return urlunparse(parsed._replace(query=new_query))
