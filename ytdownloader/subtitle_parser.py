def _safe_json_loads(json_str: str) -> Any:
    """Parse a JSON string with lenient error handling.

    Args:
        json_str: JSON-encoded string.

    Returns:
        Parsed Python object.

    Raises:
        ValueError: If *json_str* is not valid JSON.
    """
    import json as _json

    try:
        return _json.loads(json_str)
    except _json.JSONDecodeError as exc:
        raise ValueError(f"Invalid JSON: {exc}") from exc


def _get_nested(
    data: Any, key: str, default: Any = None
) -> Any:
    """Safely retrieve a top-level key from a dict.

    Args:
        data: The dict (or any object) to query.
        key: Key to look up.
        default: Value to return if *key* is absent.

    Returns:
        The value for *key*, or *default*.
    """
    if isinstance(data, dict):
        return data.get(key, default)
    return default


def _seconds_to_ms(seconds: float) -> int:
    """Convert floating-point seconds to integer milliseconds.

    Args:
        seconds: Time in seconds.

    Returns:
        Equivalent time in milliseconds (rounded to nearest integer).
    """
    return int(round(seconds * 1000))


