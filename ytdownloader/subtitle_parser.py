# Internal helpers – XML parsing
# ---------------------------------------------------------------------------


def _parse_xml_caption(xml_content: str) -> list[SubtitleCue]:
    """Extract subtitle cues from YouTube's timed-text XML format.

    YouTube's XML format wraps cues in ``<p>`` elements inside a root
    ``<transcript>`` element.  Each ``<p>`` element has ``t`` (start ms)
    and ``d`` (duration ms) attributes.  The cue text is a sequence of
    ``<s>`` (sub-word) elements concatenated together.

    Args:
        xml_content: Raw XML string from the YouTube subtitle endpoint.

    Returns:
        Ordered list of :class:`SubtitleCue` objects.
    """
    cues: list[SubtitleCue] = []

    try:
        root = ET.fromstring(xml_content)
    except ET.ParseError as exc:
        _logger.error("Failed to parse XML caption: %s", exc)
        return cues

    p_elements = root.findall(_XML_CUE_TAG)
    if not p_elements:
        p_elements = root.findall(".//" + _XML_CUE_TAG)

    for index, p_elem in enumerate(p_elements):
        try:
            cue = _xml_element_to_cue(p_elem, index)
            if cue is not None:
                cues.append(cue)
        except Exception as exc:
            _logger.warning(
                "Skipping XML cue at index %d: %s", index, exc
            )
            continue

    _logger.debug("Parsed %d XML cue(s).", len(cues))
    return cues


def _xml_element_to_cue(p_elem: ET.Element, index: int) -> Optional[SubtitleCue]:
    """Convert a single XML ``<p>`` element to a :class:`SubtitleCue`.

    Args:
        p_elem: The XML element representing one caption cue.
        index: Zero-based sequential index assigned to this cue.

    Returns:
        A :class:`SubtitleCue`, or ``None`` if the element is malformed.
    """
    start_str: str = p_elem.get("t", "")
    duration_str: str = p_elem.get("d", "")

    if not start_str:
        return None

    try:
        start_ms = int(start_str)
        duration_ms = int(duration_str) if duration_str else 0
    except ValueError:
        return None

    text_parts: list[str] = []
    for child in p_elem.iter():
        if child.tag == _XML_TEXT_TAG and child.text:
            text_parts.append(child.text or "")
        elif child.tag == _XML_CUE_TAG and child.text and child is p_elem:
            text_parts.append(child.text or "")
    raw_text = p_elem.text or ""
    for child in p_elem:
        if child.text:
            raw_text += child.text
        if child.tail:
            raw_text += child.tail

    text = raw_text.strip()
    text = _normalise_subtitle_text(text)

    end_ms = start_ms + max(duration_ms, _estimate_duration_ms(text))

    return SubtitleCue(index=index, start_ms=start_ms, end_ms=end_ms, text=text)


def _estimate_duration_ms(text: str) -> int:
    """Estimate a display duration for a text string in milliseconds.

    Uses a heuristic of 150 ms per character as a minimum, with a floor
    of 1 second and a ceiling of 5 seconds for short cues.

    Args:
        text: The subtitle text.

    Returns:
        Estimated display duration in milliseconds.
    """
    char_count = len(text)
    if char_count == 0:
        return 1000
    estimated = int(char_count * 150)
    return max(1000, min(estimated, 5000))


def _xml_cue_to_srt(cue: SubtitleCue, index: int) -> str:
    """Convert a single :class:`SubtitleCue` to an SRT entry string.

    Args:
        cue: The subtitle cue to convert.
        index: The 1-based SRT entry index.

    Returns:
        A string in SRT entry format::

            1
            00:00:01,000 --> 00:00:04,000
            Hello, world!

    """
    lines = _split_srt_text(cue.text)
    time_line = (
        f"{_format_srt_time(cue.start_ms)} --> "
        f"{_format_srt_time(cue.end_ms)}"
    )
    entry_lines = [str(index), time_line] + lines
    return "\n".join(entry_lines)


