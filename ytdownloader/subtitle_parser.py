# Internal helpers – SRT formatting
# ---------------------------------------------------------------------------


def _format_srt_time(ms: int) -> str:
    """Format a millisecond timestamp as an SRT timecode ``HH:MM:SS,mmm``.

    Handles negative values by clamping to zero.  Values exceeding 24 hours
    are allowed (SRT spec permits it) but displayed without day rollover.

    Args:
        ms: Time offset in milliseconds.

    Returns:
        A string of the form ``"HH:MM:SS,mmm"``.
    """
    ms = max(ms, 0)
    hours, remainder = divmod(ms, 3_600_000)
    minutes, remainder = divmod(remainder, 60_000)
    seconds, milliseconds = divmod(remainder, 1000)
    return f"{hours:02d}:{minutes:02d}:{seconds:02d},{milliseconds:03d}"


def _cue_to_srt_entry(cue: SubtitleCue) -> str:
    """Build a single SRT entry block from a :class:`SubtitleCue`.

    Args:
        cue: The subtitle cue.

    Returns:
        A multi-line SRT entry block string.
    """
    return _xml_cue_to_srt(cue, cue.index + 1)


def _split_srt_text(text: str, max_chars_per_line: int = 42) -> list[str]:
    """Split subtitle text into SRT-compatible lines.

    SRT convention limits each line to roughly 42 characters and at most
    two lines per cue.  Long words are kept intact where possible.

    Args:
        text: The raw subtitle text (may contain ``\\n`` for hard breaks).
        max_chars_per_line: Maximum characters per output line.

    Returns:
        A list of 1 or 2 strings.
    """
    hard_blocks = text.split("\\n")
    result: list[str] = []
    for block in hard_blocks:
        if len(block) <= max_chars_per_line:
            result.append(block)
        else:
            wrapped = _soft_wrap(block, max_chars_per_line)
            result.extend(wrapped[:2])
    return result[:2] if result else [""]


def _soft_wrap(text: str, max_chars: int) -> list[str]:
    """Wrap *text* into lines of at most *max_chars* characters.

    Breaks are inserted at whitespace boundaries.  Falls back to a hard
    split at *max_chars* when no whitespace is available.

    Args:
        text: Text to wrap.
        max_chars: Maximum line length.

    Returns:
        List of wrapped lines.
    """
    words = text.split()
    lines: list[str] = []
    current = ""
    for word in words:
        if current and len(current) + 1 + len(word) > max_chars:
            lines.append(current)
            current = word
        else:
            current = f"{current} {word}" if current else word
    if current:
        lines.append(current)
    if not lines:
        lines = [text[:max_chars]]
    return lines


def _normalise_subtitle_text(text: str) -> str:
    """Clean up raw caption text into a display-ready string.

    - Strips XML/HTML-like tags that may appear in the text.
    - Decodes common HTML entities.
    - Collapses runs of whitespace.
    - Removes common non-speech filler tags used by YouTube ASR.

    Args:
        text: Raw caption text.

    Returns:
        Cleaned caption text.
    """
    if not text:
        return ""
    text = re.sub(r"<[^>]+>", "", text)
    text = re.sub(r"&amp;", "&", text)
    text = re.sub(r"&lt;", "<", text)
    text = re.sub(r"&gt;", ">", text)
    text = re.sub(r"&quot;", '"', text)
    text = re.sub(r"&#39;", "'", text)
    text = re.sub(r"&nbsp;", " ", text)
    text = re.sub(r"\s+", " ", text).strip()
    return text


